// Generates api/_engine-data.js from the live index.html so the new server
// engine routes complaints with exactly the same authority data and rules as
// the current site. index.html stays the single source of truth: re-run this
// after editing AUTHORITIES / CHAIN / CAT_SUBS there.
//
//   node scripts/extract-engine-data.mjs          # write api/_engine-data.js
//   node scripts/extract-engine-data.mjs --check  # exit 1 if it is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'index.html'), 'utf8');
const OUT = join(root, 'api', '_engine-data.js');

// Returns the source of a `const|var NAME = <literal>;` declaration by brace matching.
function literal(name) {
  const m = html.match(new RegExp('(?:const|var|let)\\s+' + name + '\\s*=\\s*'));
  if (!m) throw new Error('not found: ' + name);
  let i = m.index + m[0].length;
  const open = html[i], close = open === '{' ? '}' : ']';
  let depth = 0, str = null;
  for (let j = i; j < html.length; j++) {
    const c = html[j];
    if (str) { if (c === '\\') { j++; continue; } if (c === str) str = null; continue; }
    if (c === '"' || c === "'" || c === '`') { str = c; continue; }
    if (c === open) depth++;
    else if (c === close && --depth === 0) return html.slice(i, j + 1);
  }
  throw new Error('unterminated: ' + name);
}

// Returns the source of a top-level `function NAME(...) { ... }`.
function fn(name) {
  const start = html.indexOf('function ' + name + '(');
  if (start < 0) throw new Error('not found: function ' + name);
  let i = html.indexOf('{', start), depth = 0, str = null;
  for (let j = i; j < html.length; j++) {
    const c = html[j];
    if (str) { if (c === '\\') { j++; continue; } if (c === str) str = null; continue; }
    if (c === '"' || c === "'" || c === '`') { str = c; continue; }
    if (c === '/' && html[j + 1] !== '/' && html[j + 1] !== '*' && /[(,=:!&|?{};\s]/.test(html[j - 1])) {
      // regex literal: skip to its closing slash
      for (j++; j < html.length && html[j] !== '/'; j++) { if (html[j] === '\\') j++; if (html[j] === '[') { while (html[++j] !== ']') if (html[j] === '\\') j++; } }
      continue;
    }
    if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return html.slice(start, j + 1);
  }
  throw new Error('unterminated: function ' + name);
}

function enString(key) {
  const m = html.match(new RegExp(key + ':"((?:[^"\\\\]|\\\\.)*)"'));
  if (!m) throw new Error('not found: ' + key);
  return JSON.parse('"' + m[1] + '"');
}

const out = `// AUTO-GENERATED by scripts/extract-engine-data.mjs from index.html — do not edit by hand.
/* eslint-disable */
export const AUTHORITIES = ${literal('AUTHORITIES')};
export const CHAIN = ${literal('CHAIN')};
export const CAT_SUBS = ${literal('CAT_SUBS')};
export const CAT_GROUPS = ${literal('CAT_GROUPS')};
export const _CAT_TOPIC = ${literal('_CAT_TOPIC')};
export const _TGT_TOPIC = ${literal('_TGT_TOPIC')};
const _PROV_NAMES = ${literal('_PROV_NAMES')};
const _PC_FIRST = ${literal('_PC_FIRST')};
export const _PROV_LABEL = ${literal('_PROV_LABEL')};
export ${fn('_detectProvince')}
export ${fn('_isFederalAuth')}
export ${fn('_isMail')}
export ${fn('_authUrl')}
export const CONF_SUBJ = ${JSON.stringify(enString('conf_subj'))};
export const CONF_BODY = ${JSON.stringify(enString('conf_body'))};
`;

if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(OUT, 'utf8'); } catch {}
  if (cur !== out) { console.error('api/_engine-data.js is out of date — run: node scripts/extract-engine-data.mjs'); process.exit(1); }
  console.log('api/_engine-data.js is up to date');
} else {
  writeFileSync(OUT, out);
  console.log('wrote', OUT, (out.length / 1024).toFixed(1) + ' KB');
}
